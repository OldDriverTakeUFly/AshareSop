# 未匹配的板块归入此分类
_OTHER_SECTOR = "综合"


def normalize_sector_name(raw_name: str) -> str:
    """把任意口径的板块名归一化到申万一级.

    参数：
        raw_name: 原始板块名（zt_pool/fund_flow/sw_daily 任意口径）

    返回：
        申万一级板块名（如"电子""医药生物"）；未匹配返回"综合"
    """
    if not raw_name:
        return _OTHER_SECTOR

    name = raw_name.strip()
    for l1_name, keywords in _SECTOR_L1_KEYWORDS:
        if any(kw in name for kw in keywords):
            return l1_name
    return _OTHER_SECTOR


def normalize_sector_map(names: list[str]) -> dict[str, str]:
    """批量归一化板块名.

    返回 {原始名: 申万一级} 映射字典。
    """
    return {name: normalize_sector_name(name) for name in names}
